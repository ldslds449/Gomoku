import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
const run = (cmd, args) => execFileSync(cmd, args, { stdio: "inherit" });
run("cargo", [
  "build",
  "--locked",
  "--release",
  "--target",
  "wasm32-unknown-unknown",
]);
run("wasm-bindgen", [
  "--target",
  "no-modules",
  "--no-typescript",
  "--out-dir",
  "target/web",
  "target/wasm32-unknown-unknown/release/gomoku.wasm",
]);
const glue = readFileSync("target/web/gomoku.js", "utf8");
const wasm = readFileSync("target/web/gomoku_bg.wasm").toString("base64");
const worker = readFileSync("src/worker.js", "utf8");
const source =
  glue +
  "\nconst engineReady=wasm_bindgen({module_or_path:Uint8Array.from(atob(" +
  JSON.stringify(wasm) +
  "), c=>c.charCodeAt(0))});\n" +
  worker;
writeFileSync(
  "engine.bundle.js",
  "// Generated by npm run build.\nconst gomokuWorkerSource=" +
    JSON.stringify(source) +
    ";\n",
);
